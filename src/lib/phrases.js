// ── Детерминированный выбор ───────────────────────────────────────────────────

function hashIndex(seed, stepIndex, poolLength) {
  if (poolLength <= 0) return 0
  const mixed = Math.abs((seed + stepIndex * 2654435761) | 0)
  return mixed % poolLength
}

function selectPhrase(pool, seed, stepIndex, name) {
  const idx = hashIndex(seed, stepIndex, pool.length)
  let phrase = pool[idx] || pool[0]
  if (phrase.includes('{name}')) {
    if (name) {
      phrase = phrase.replace('{name}', name)
    } else {
      // Вариант без имени выбираем тем же хешем, иначе одна фраза звучала бы за все.
      const noName = pool.filter(p => !p.includes('{name}'))
      if (noName.length) phrase = noName[hashIndex(seed, stepIndex, noName.length)] || noName[0]
    }
  }
  return phrase
}

/** Фирменный пул шага: сначала вид чая, потом общий набор пака. */
function funPool(kind, pack, family) {
  const prophet = pack === PACK_SUNBOY
  if (kind === 'steep') {
    const byFamily = family && (prophet ? PROPHET_FAMILY_STEEP : FAMILY_STEEP)[family]
    if (byFamily && byFamily.length) return byFamily
    return prophet ? PROPHET_STEEP : STEEP_FUN
  }
  if (kind === 'rinse') return prophet ? PROPHET_RINSE : RINSE_FUN
  return prophet ? PROPHET_FINISH : FINISH_FUN
}

/**
 * @param kind 'steep' | 'rinse' | 'finish'
 * @param opts { pack, teaKey }
 */
export function teaPhrase(kind, stepIndex, seed, name, opts = {}) {
  const pack = opts.pack || PACK_CLASSIC
  if (pack === PACK_NEUTRAL) return NEUTRAL[kind][0]

  const family = teaFamily(opts.teaKey)
  const fun = funPool(kind, pack, family)

  // Фирменные фразы чаще, когда есть что показать: набор пака или вида чая.
  const tuned = pack === PACK_SUNBOY || (kind === 'steep' && !!family)
  const isFun = (stepIndex + seed) % (tuned ? 2 : 3) === 0

  const pool = isFun ? fun : NEUTRAL[kind]
  if (!pool || !pool.length) return 'Чай готов'
  return selectPhrase(pool, seed, stepIndex, name)
}

export function teaNotificationTitle(pack) {
  return pack === PACK_SUNBOY ? '🍵 Так предсказано' : '🍵 Чай готов'
}

